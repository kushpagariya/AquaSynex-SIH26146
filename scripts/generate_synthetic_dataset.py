    def _fund_entity_if_needed(self, entity: SyntheticEntity, min_sats: int = 50_000_000) -> UTXO:
        """Ensure an entity has a spendable UTXO with >= min_sats and return it."""
        spendable = entity.get_spendable_utxo(min_sats)
        if spendable is None:
            init_txid = generate_txid(self.rng, f"topup_{entity.entity_id}_{len(entity.utxos)}_{self.scenario_counter}")
            topup_sats = max(min_sats * 2, 100_000_000)
            stype = self.rng.choice(["P2WPKH", "P2PKH", "P2SH"])
            fresh_addr = generate_address(self.rng, stype)
            entity.add_address(fresh_addr)
            self.address_to_entity[fresh_addr] = entity.entity_id
            
            utxo = UTXO(
                txid=init_txid,
                output_index=0,
                address=fresh_addr,
                amount_satoshi=topup_sats,
                entity_id=entity.entity_id
            )
            entity.add_utxo(utxo)
            self.utxo_pool[utxo.key] = utxo
            return utxo
        return spendable

    def _create_transaction(
        self,
        txid: str,
        timestamp: datetime.datetime,
        inputs: List[Tuple[UTXO, int]],
        outputs: List[Tuple[str, int, bool]],
        fee: int,
        scenario_id: str,
        behavior_type: str,
        ground_truth: int,
        primary_entity_id: str,
        script_type: str = "P2WPKH",
        network_anomaly: bool = False,
        custom_net_params: Optional[Dict[str, Any]] = None
    ) -> str:
        """Atomic transaction registration with strict UTXO conservation and SIH formatting."""
        total_in = sum(u.amount_satoshi for u, _ in inputs)
        total_out = sum(amt for _, amt, _ in outputs)
        
        # Strict UTXO conservation: total_in = total_out + fee
        assert total_in == total_out + fee, f"Conservation violation in {txid}: in={total_in}, out={total_out}, fee={fee}"
        assert fee >= 0, f"Negative fee in {txid}: {fee}"
        
        if len(self.tx_records) % 150 == 0 and len(self.tx_records) > 0:
            self.block_height += 1

        tx_size_bytes = 148 * len(inputs) + 34 * len(outputs) + 10

        # 1. Canonical Transaction Record
        self.tx_records.append({
            "txid": txid,
            "block_height": self.block_height,
            "timestamp": timestamp.isoformat(),
            "input_count": len(inputs),
            "output_count": len(outputs),
            "total_input_value_satoshi": total_in,
            "total_output_value_satoshi": total_out,
            "fee_satoshi": fee,
            "transaction_size_bytes": tx_size_bytes,
            "script_type": script_type,
            "scenario_id": scenario_id
        })

        # 2. Normalized Transaction Inputs
        in_addrs = []
        in_amts = []
        for idx, (utxo, _) in enumerate(inputs):
            self.input_records.append({
                "txid": txid,
                "input_index": idx,
                "address": utxo.address,
                "amount_satoshi": utxo.amount_satoshi,
                "prev_txid": utxo.txid,
                "prev_output_index": utxo.output_index,
                "scenario_id": scenario_id
            })
            in_addrs.append(utxo.address)
            in_amts.append(utxo.amount_satoshi)
            
            # Remove spent UTXO in O(1)
            self.utxo_pool.pop(utxo.key, None)
            ent = self.entities.get(utxo.entity_id)
            if ent:
                ent.remove_utxo(utxo)

        # 3. Normalized Transaction Outputs
        out_addrs = []
        out_amts = []
        for idx, (out_addr, out_amt, is_change) in enumerate(outputs):
            self.output_records.append({
                "txid": txid,
                "output_index": idx,
                "address": out_addr,
                "amount_satoshi": out_amt,
                "script_type": script_type,
                "is_change": is_change,
                "scenario_id": scenario_id
            })
            out_addrs.append(out_addr)
            out_amts.append(out_amt)
            
            # Resolve recipient entity in O(1)
            recip_eid = primary_entity_id if is_change else self.address_to_entity.get(out_addr)
            if not recip_eid:
                recip_ent = self.rng.choice(list(self.entities.values()))
                recip_eid = recip_ent.entity_id
                recip_ent.add_address(out_addr)
                self.address_to_entity[out_addr] = recip_eid
            
            recip_ent = self.entities.get(recip_eid)
            new_utxo = UTXO(
                txid=txid,
                output_index=idx,
                address=out_addr,
                amount_satoshi=out_amt,
                entity_id=recip_eid
            )
            if recip_ent:
                recip_ent.add_utxo(new_utxo)
            self.utxo_pool[new_utxo.key] = new_utxo

        # 4. Network Layer Event
        prim_ent = self.entities.get(primary_entity_id)
        if custom_net_params:
            src_ip = custom_net_params.get("src_ip", generate_ip(self.rng))
            src_port = custom_net_params.get("src_port", self.rng.randint(1024, 65535))
            dst_ip = custom_net_params.get("dst_ip", generate_ip(self.rng))
            dst_port = custom_net_params.get("dst_port", 8333)
            country = custom_net_params.get("country", choose_weighted(self.rng, COUNTRIES))
            asn = custom_net_params.get("asn", choose_weighted(self.rng, [(a[0], a[2]) for a in ASNS]))
        elif network_anomaly:
            src_ip = generate_ip(self.rng)  # Rapid IP hopping
            # Suspicious nodes: ~75% standard 8333 to blend into P2P traffic, ~25% alt/rpc ports
            dst_port = choose_weighted(self.rng, [(8333, 0.75), (18333, 0.12), (8332, 0.08), (8080, 0.03), (9333, 0.02)])
            # Source ports: 80% ephemeral, 20% privacy proxy / Tor
            if self.rng.random() < 0.20:
                src_port = self.rng.choice([9050, 9150, 443, 8080])
            else:
                src_port = self.rng.randint(1024, 65535)
            dst_ip = generate_ip(self.rng)
            country = self.rng.choice(["SC", "BZ", "PA", "RU", "IR", "NL", "DE", "US", "SG", "GB", "CH"])
            asn = self.rng.choice([9009, 60068, 24940, 14061, 15169, 16509])
        else:
            src_ip = generate_ip(self.rng, prim_ent.ip_subnet if prim_ent else None)
            # Benign nodes: ~82% 8333, ~6% testnet 18333, ~6% RPC 8332, ~6% alt peer ports (8080, 9333)
            dst_port = choose_weighted(self.rng, [(8333, 0.82), (18333, 0.06), (8332, 0.06), (8080, 0.03), (9333, 0.03)])
            # Source ports: 96% ephemeral, 4% privacy proxy / Tor (legitimate privacy users)
            if self.rng.random() < 0.04:
                src_port = self.rng.choice([9050, 9150, 443, 8080])
            else:
                src_port = self.rng.randint(1024, 65535)
