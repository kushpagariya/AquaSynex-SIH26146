    def generate_transaction_burst(self, count: int = 4):
        scenario_id = self._next_scenario_id("burst")
        entity = self.rng.choice(list(self.entities.values()))
        self._fund_entity_if_needed(entity, min_sats=50_000_000)
        net_anomaly = self.rng.random() < 0.5
        
        for b in range(count):
            utxo = self._fund_entity_if_needed(entity, min_sats=50_000_000)
            txid = generate_txid(self.rng, f"burst_{scenario_id}_{b}")
            fee = self.rng.randint(5_000, 20_000)
            avail = utxo.amount_satoshi - fee
            # Continuous spend fraction: 0.25 to 0.75
