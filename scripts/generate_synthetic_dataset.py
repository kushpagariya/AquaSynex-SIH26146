    def generate_normal_transaction(self):
        scenario_id = self._next_scenario_id("normal")
        sender = self.rng.choice([e for e in self.entities.values() if e.entity_type != "exchange"])
        
        # Realistic UTXO count distribution for benign transactions:
        # 68% 1-in payment, 18% 2-in payment, 6% 3-in payment, 8% 1-in sweep (0 change)
        in_mode = choose_weighted(self.rng, [
            ("1_in_payment", 0.68),
            ("2_in_payment", 0.18),
            ("3_in_payment", 0.06),
            ("1_in_sweep", 0.08)
        ])
        
        if in_mode == "1_in_payment":
            u = self._fund_entity_if_needed(sender, min_sats=30_000_000)
            inputs = [(u, u.amount_satoshi)]
        elif in_mode == "2_in_payment":
            self._fund_entity_if_needed(sender, min_sats=15_000_000)
            utxos = sender.get_n_utxos(2)
            if len(utxos) < 2:
                self._fund_entity_if_needed(sender, min_sats=15_000_000)
                utxos = sender.get_n_utxos(2)
            inputs = [(u, u.amount_satoshi) for u in utxos[:2]]
        elif in_mode == "3_in_payment":
            self._fund_entity_if_needed(sender, min_sats=10_000_000)
            utxos = sender.get_n_utxos(3)
            inputs = [(u, u.amount_satoshi) for u in utxos[:3]]
        else: # 1_in_sweep
            u = self._fund_entity_if_needed(sender, min_sats=20_000_000)
            inputs = [(u, u.amount_satoshi)]

        total_in = sum(amt for _, amt in inputs)
        fee = self.rng.randint(2_000, 15_000)
        avail = total_in - fee
        assert avail > 0
        
        recipient = self.rng.choice([e for e in self.entities.values() if e.entity_id != sender.entity_id])
        txid = generate_txid(self.rng, f"norm_{scenario_id}")
        self.current_time += datetime.timedelta(seconds=self.rng.randint(5, 90))
        
        if in_mode == "1_in_sweep":
            # Direct sweep / payment without change
            outputs = [(recipient.primary_address, avail, False)]
        else:
            # Continuous payment fraction between 0.15 and 0.85
            pay_fraction = self.rng.uniform(0.15, 0.85)
            send_amt = max(10_000, int(avail * pay_fraction))
            change_amt = avail - send_amt
            if change_amt < 5_000:
                outputs = [(recipient.primary_address, avail, False)]
            else:
                change_addr = generate_address(self.rng, "P2WPKH")
                sender.add_address(change_addr)
                self.address_to_entity[change_addr] = sender.entity_id
                outputs = [
                    (recipient.primary_address, send_amt, False),
                    (change_addr, change_amt, True)
                ]
        
        self._create_transaction(
            txid=txid,
            timestamp=self.current_time,
            inputs=inputs,
            outputs=outputs,
            fee=fee,
            scenario_id=scenario_id,
            behavior_type="normal",
            ground_truth=0,
            primary_entity_id=sender.entity_id,
            script_type="P2WPKH"
        )

