BECH32_CHARS = "023456789acdefghjklmnpqrstuvwxyz"
BASE58_CHARS = "123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz"

def generate_address(rng: random.Random, script_type: str = "P2WPKH") -> str:
    """Generate a synthetic Bitcoin address according to script type."""
    if script_type == "P2WPKH":
        suffix = "".join(rng.choice(BECH32_CHARS) for _ in range(38))
        return f"bc1q{suffix}"
    elif script_type == "P2SH":
        suffix = "".join(rng.choice(BASE58_CHARS) for _ in range(33))
        return f"3{suffix}"
    else:
        suffix = "".join(rng.choice(BASE58_CHARS) for _ in range(33))
        return f"1{suffix}"

def generate_txid(rng: random.Random, salt: str) -> str:
    """Generate a synthetic 64-hex-character Bitcoin transaction hash."""
    seed_str = f"tx_{salt}_{rng.getrandbits(128)}_{rng.random()}"
    return hashlib.sha256(seed_str.encode("utf-8")).hexdigest()

def generate_ip(rng: random.Random, subnet: Optional[str] = None) -> str:
    """Generate a realistic synthetic IPv4 address."""
    if subnet:
        return f"{subnet}.{rng.randint(2, 254)}"
    first_octet = rng.choice([24, 31, 45, 51, 62, 78, 85, 93, 104, 142, 168, 178, 185, 198, 203])
    return f"{first_octet}.{rng.randint(1, 254)}.{rng.randint(1, 254)}.{rng.randint(2, 254)}"

def choose_weighted(rng: random.Random, items_with_weights: List[Tuple[Any, float]]) -> Any:
    items, weights = zip(*items_with_weights)
    return rng.choices(items, weights=weights, k=1)[0]

class UTXO:
    def __init__(self, txid: str, output_index: int, address: str, amount_satoshi: int, entity_id: str):
        self.txid = txid
        self.output_index = output_index
        self.address = address
        self.amount_satoshi = amount_satoshi
        self.entity_id = entity_id

    @property
    def key(self) -> Tuple[str, int]:
        return (self.txid, self.output_index)

class SyntheticEntity:
    def __init__(self, entity_id: str, entity_type: str, primary_address: str, rng: random.Random):
        self.entity_id = entity_id
        self.entity_type = entity_type
        self.primary_address = primary_address
        self.addresses = [primary_address]
        self.utxos: Dict[Tuple[str, int], UTXO] = {}
        self.ip_subnet = f"{rng.choice([45, 78, 104, 168, 185])}.{rng.randint(10, 200)}.{rng.randint(1, 250)}"
        self.primary_country = choose_weighted(rng, COUNTRIES)
        self.primary_asn = choose_weighted(rng, [(asn[0], asn[2]) for asn in ASNS])
        self.created_at = None

    def add_address(self, address: str):
        if address not in self.addresses:
            self.addresses.append(address)

    def add_utxo(self, utxo: UTXO):
        self.utxos[utxo.key] = utxo

    def remove_utxo(self, utxo: UTXO):
        self.utxos.pop(utxo.key, None)

    def get_any_utxo(self) -> Optional[UTXO]:
        if not self.utxos:
            return None
        return next(iter(self.utxos.values()))

    def get_spendable_utxo(self, min_satoshi: int) -> Optional[UTXO]:
        for u in self.utxos.values():
            if u.amount_satoshi >= min_satoshi:
                return u
        return None

    def get_n_utxos(self, n: int) -> List[UTXO]:
        return list(self.utxos.values())[:n]

