        self._fund_entity_if_needed(sender, min_sats=200_000_000)
        
        num_ins = min(len(sender.utxos), self.rng.randint(2, 5))
        ins_utxos = sender.get_n_utxos(num_ins)
        ins = [(u, u.amount_satoshi) for u in ins_utxos]
        total_in = sum(u.amount_satoshi for u, _ in ins)
        
        fee = self.rng.randint(10_000, 50_000)
        avail = total_in - fee
        
        num_outs = self.rng.randint(5, 15)
        # Continuous change fraction: 0.15 to 0.65
        change_frac = self.rng.uniform(0.15, 0.65)
        change_amt_target = int(avail * change_frac)
        payout_avail = avail - change_amt_target
        
        amt_per_out = payout_avail // num_outs
        outputs = []
        for _ in range(num_outs):
            recip = self.rng.choice(list(self.entities.values()))
            outputs.append((recip.primary_address, amt_per_out, False))
            
