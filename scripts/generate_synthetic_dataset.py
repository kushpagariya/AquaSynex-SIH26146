    def generate(self):
        print(f"[*] Bootstrapping entities & initial UTXO pool (seed={self.seed})...", flush=True)
        self.bootstrap_entities_and_utxos()
        
        scenario_handlers = {
            "normal": self.generate_normal_transaction,
            "benign_high_volume": self.generate_benign_high_volume_transaction,
            "transaction_burst": lambda: self.generate_transaction_burst(count=self.rng.randint(3, 5)),
            "high_fan_in": self.generate_high_fan_in,
            "high_fan_out": self.generate_high_fan_out,
            "rapid_multihop": lambda: self.generate_rapid_multihop(hops=self.rng.randint(3, 5)),
            "peeling_chain": lambda: self.generate_peeling_chain(steps=self.rng.randint(4, 6)),
            "mixing_like": self.generate_mixing_like_transaction,
            "coordinated_activity": self.generate_coordinated_activity,
            "amount_anomaly": self.generate_amount_anomaly,
            "temporal_anomaly": self.generate_temporal_anomaly
        }
        
        scenario_keys = list(self.scenario_mix.keys())
        scenario_weights = [self.scenario_mix[k] for k in scenario_keys]
        
        print(f"[*] Generating {self.total_transactions:,} synthetic transactions across scenarios...", flush=True)
        step = max(1, self.total_transactions // 10)
        
        while len(self.tx_records) < self.total_transactions:
            chosen_scenario = self.rng.choices(scenario_keys, weights=scenario_weights, k=1)[0]
            handler = scenario_handlers[chosen_scenario]
            handler()
            
            if len(self.tx_records) % step == 0 or len(self.tx_records) >= self.total_transactions:
                print(f"    -> Progress: {min(len(self.tx_records), self.total_transactions):,} / {self.total_transactions:,} transactions generated.", flush=True)

        if len(self.tx_records) > self.total_transactions:
            cutoff = self.total_transactions
            valid_txids = set(t["txid"] for t in self.tx_records[:cutoff])
            self.tx_records = self.tx_records[:cutoff]
            self.input_records = [r for r in self.input_records if r["txid"] in valid_txids]
            self.output_records = [r for r in self.output_records if r["txid"] in valid_txids]
            self.network_records = [r for r in self.network_records if r["txid"] in valid_txids]
            self.label_records = [r for r in self.label_records if r["txid"] in valid_txids]
            self.sih_records = [r for r in self.sih_records if r["txid"] in valid_txids]

        print(f"[+] Generation complete: {len(self.tx_records):,} transactions, {len(self.input_records):,} inputs, {len(self.output_records):,} outputs, {len(self.network_records):,} network events.", flush=True)

